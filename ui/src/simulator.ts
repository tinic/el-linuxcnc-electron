// A stand-in machine for developing the panel in a browser. It keeps plausible state, moves the
// slides while jogging and answers plan requests with a simple, clearly simulated tool path. It
// never pretends to be the real cycle generator: real G-code only comes from the C++ core.

import type { Transport, Listener } from './bridge'
import type {
  CyclePlan,
  Direction,
  Feed,
  JogButton,
  MachineStatus,
  Segment,
  Settings,
  ToMachine,
} from './protocol'

const tickMs = 33
const deadmanMs = 150

function defaultSettings(): Settings {
  return {
    diameter_mode: true,
    metric_on_startup: true,
    thread_preset_tab: 0,
    turning_preset_tab: 0,
    pitch_preset_tabs: [0, 0],
    machine: {
      encoder_scale_z: 0.001,
      encoder_scale_x: -0.001,
      pitches: { x: 0.02, z: 0.05 },
      tools: Array.from({ length: 10 }, (_, id) => ({
        id,
        offset_x: 0,
        offset_z: 0,
        description: id === 0 ? 'Reference Tool' : '',
      })),
      current_tool: 0,
    },
  }
}

function engagement(feed: Feed, direction: Direction): MachineStatus['leadscrew'] {
  const moving = direction === 'forward' || direction === 'reverse'
  const powered = direction !== 'idle'
  const z = feed !== 'cross'
  const x = feed !== 'longitudinal'
  return {
    cycle_control: false,
    z_feed: 0,
    x_feed: 0,
    z_driver_enabled: powered && z,
    x_driver_enabled: powered && x,
    z_follows_spindle: moving && z,
    x_follows_spindle: moving && x,
  }
}

function simulatedPlan(kind: CyclePlan['kind'], x: number, z: number): CyclePlan {
  const segments: Segment[] = []
  let line = 0
  for (let pass = 1; pass <= 4; pass += 1) {
    const depth = x - pass * 0.3
    segments.push({ kind: 'rapid', from: { x: x + 1, z: 2 }, to: { x: depth, z: 2 }, line: line++ })
    segments.push({ kind: 'thread', from: { x: depth, z: 2 }, to: { x: depth, z: z - 20 }, line: line++ })
    segments.push({ kind: 'rapid', from: { x: depth, z: z - 20 }, to: { x: x + 1, z: z - 20 }, line: line++ })
    segments.push({ kind: 'rapid', from: { x: x + 1, z: z - 20 }, to: { x: x + 1, z: 2 }, line: line++ })
  }
  return {
    kind,
    issues: [],
    error: '',
    gcode: ['(simulated tool path - not generated by the cycle core)'],
    backplot: { segments, bounds: { min: { x: x - 1.2, z: z - 20 }, max: { x: x + 1, z: 2 } } },
    start: { x, z },
  }
}

export function createSimulator(): Transport {
  const listeners: Listener[] = []
  const settings = defaultSettings()
  const offsets = { x: 0, z: 0, a: 0 }
  const machine = { x: 12.5, z: -3, revs: 0, rpm: 0 }
  const held = new Map<JogButton, { since: number; seen: number }>()
  const status: MachineStatus = {
    readout: { x: 0, z: 0, a_degrees: 0, rpm: 0 },
    mode: 'manual',
    feed: 'longitudinal',
    direction: 'idle',
    pitches: { ...settings.machine.pitches },
    leadscrew: engagement('longitudinal', 'idle'),
    task: { connected: true, program_running: false, error: false },
  }

  const emit = (message: Parameters<Listener>[0]): void => {
    for (const listener of listeners) {
      listener(message)
    }
  }
  const tool = (): { offset_x: number; offset_z: number } =>
    settings.machine.tools.find((t) => t.id === settings.machine.current_tool) ?? {
      offset_x: 0,
      offset_z: 0,
    }

  const tick = (): void => {
    const now = performance.now()
    for (const [button, state] of held) {
      if (now - state.seen > deadmanMs) {
        held.delete(button)
        continue
      }
      const speed = Math.min(((now - state.since) / 1000) * 3, button.startsWith('x') ? 3 : 6)
      const step = (speed * tickMs) / 1000
      if (button === 'x_minus') machine.x -= step
      if (button === 'x_plus') machine.x += step
      if (button === 'z_minus') machine.z -= step
      if (button === 'z_plus') machine.z += step
    }
    machine.rpm = 0
    status.readout = {
      x: machine.x - offsets.x + tool().offset_x,
      z: machine.z - offsets.z + tool().offset_z,
      a_degrees: ((((machine.revs - offsets.a) % 1) + 1) % 1) * 360,
      rpm: machine.rpm,
    }
    emit({ type: 'status', status: structuredClone(status) })
  }

  const handle = (message: ToMachine): void => {
    switch (message.type) {
      case 'ready':
        emit({ type: 'settings', settings: structuredClone(settings) })
        emit({ type: 'log', lines: ['Simulator: no machine connected. Cycles are not generated.'] })
        break
      case 'select_mode':
        status.mode = message.mode
        if (message.mode === 'cycle') {
          status.feed = 'back_compound'
          status.direction = 'hold'
        }
        status.leadscrew = engagement(status.feed, status.direction)
        held.clear()
        break
      case 'set_feed':
        status.feed = message.feed
        status.leadscrew = engagement(status.feed, status.direction)
        break
      case 'set_direction':
        status.direction = message.direction
        status.leadscrew = engagement(status.feed, status.direction)
        break
      case 'set_pitches':
        status.pitches = { ...message.pitches }
        settings.machine.pitches = { ...message.pitches }
        emit({ type: 'settings', settings: structuredClone(settings) })
        break
      case 'set_axis':
        if (message.axis === 'x') offsets.x = machine.x + tool().offset_x - message.value
        if (message.axis === 'z') offsets.z = machine.z + tool().offset_z - message.value
        if (message.axis === 'a') offsets.a = machine.revs - message.value / 360
        break
      case 'jog':
        if (status.mode !== 'manual') break
        if (message.held) {
          const now = performance.now()
          const state = held.get(message.button)
          held.set(message.button, { since: state?.since ?? now, seen: now })
        } else {
          held.delete(message.button)
        }
        break
      case 'jog_release_all':
        held.clear()
        break
      case 'select_tool':
        settings.machine.current_tool = message.id
        emit({ type: 'settings', settings: structuredClone(settings) })
        break
      case 'set_tools':
        settings.machine.tools = structuredClone(message.tools)
        emit({ type: 'settings', settings: structuredClone(settings) })
        break
      case 'set_preferences': {
        const p = message.preferences
        settings.diameter_mode = p.diameter_mode
        settings.metric_on_startup = p.metric_on_startup
        settings.thread_preset_tab = p.thread_preset_tab
        settings.turning_preset_tab = p.turning_preset_tab
        settings.pitch_preset_tabs = p.pitch_preset_tabs
        settings.machine.encoder_scale_z = p.encoder_scale_z
        settings.machine.encoder_scale_x = p.encoder_scale_x
        emit({ type: 'settings', settings: structuredClone(settings) })
        break
      }
      case 'plan_threading':
      case 'plan_turning':
        emit({
          type: 'plan',
          plan: simulatedPlan(
            message.type === 'plan_threading' ? 'threading' : 'turning',
            status.readout.x,
            status.readout.z,
          ),
        })
        break
      case 'start_cycle':
        emit({ type: 'notice', level: 'info', text: 'Simulator: cycle not run.' })
        break
      case 'abort_cycle':
      case 'quit':
        break
    }
  }

  window.setInterval(tick, tickMs)
  return {
    simulated: true,
    send: (message): void => {
      // Asynchronous like the real bridge, so the panel never relies on synchronous replies.
      queueMicrotask(() => {
        handle(message)
      })
    },
    listen: (listener): void => {
      listeners.push(listener)
    },
  }
}
